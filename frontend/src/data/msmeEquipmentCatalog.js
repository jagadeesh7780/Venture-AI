/**
 * Resolves the closest category key from user input string.
 */
export const resolveCategoryKey = (input = '') => {
  const t = String(input).toLowerCase();
  if (t.includes('boutique') || t.includes('fashion') || t.includes('garment') || t.includes('cloth') || t.includes('tailor') || t.includes('dress') || t.includes('apparel')) {
    return 'boutique';
  }
  if (t.includes('cafe') || t.includes('coffee') || t.includes('roast') || t.includes('espresso') || t.includes('tea') || t.includes('brew')) {
    return 'cafe';
  }
  if (t.includes('bakery') || t.includes('cake') || t.includes('pastry') || t.includes('bread') || t.includes('confection') || t.includes('biscuit')) {
    return 'bakery';
  }
  if (t.includes('restaurant') || t.includes('dining') || t.includes('food') || t.includes('eatery') || t.includes('kitchen') || t.includes('bistro') || t.includes('dhaba') || t.includes('hotel')) {
    return 'restaurant';
  }
  if (t.includes('gym') || t.includes('fitness') || t.includes('workout') || t.includes('crossfit') || t.includes('athletic') || t.includes('weight')) {
    return 'gym';
  }
  if (t.includes('salon') || t.includes('spa') || t.includes('beauty') || t.includes('hair') || t.includes('skin') || t.includes('cosmetic') || t.includes('barber')) {
    return 'salon';
  }
  if (t.includes('supermarket') || t.includes('grocery') || t.includes('mart') || t.includes('store') || t.includes('retail') || t.includes('provision')) {
    return 'supermarket';
  }
  if (t.includes('clinic') || t.includes('medical') || t.includes('doctor') || t.includes('hospital') || t.includes('health') || t.includes('diagnostic')) {
    return 'clinic';
  }
  if (t.includes('tech') || t.includes('electronic') || t.includes('mobile') || t.includes('phone') || t.includes('gadget') || t.includes('laptop') || t.includes('computer')) {
    return 'tech';
  }
  if (t.includes('auto') || t.includes('car') || t.includes('garage') || t.includes('motor') || t.includes('vehicle') || t.includes('mechanic') || t.includes('detailing') || t.includes('bike')) {
    return 'auto';
  }
  if (t.includes('pharmacy') || t.includes('chemist') || t.includes('drug') || t.includes('medicine') || t.includes('pharma') || t.includes('medstore')) {
    return 'pharmacy';
  }
  if (t.includes('laundry') || t.includes('dry clean') || t.includes('washing') || t.includes('laundromat') || t.includes('pressing') || t.includes('steam iron')) {
    return 'laundry';
  }
  return 'general';
};

/**
 * Returns instant, 0ms latency MSME-compliant equipment list for any business input.
 */
export const getInstantMSMEEquipment = (businessName = '', category = '', availableEquipment = []) => {
  const key = resolveCategoryKey(`${businessName} ${category}`);
  const profile = MSME_EQUIPMENT_CATALOG[key] || MSME_EQUIPMENT_CATALOG.general;
  const availLower = availableEquipment.map((a) => String(a).toLowerCase().trim());

  let totalCost = 0;
  let missingCost = 0;
  let ownedCount = 0;

  const equipmentList = profile.equipment.map((item) => {
    const isOwned = availLower.some((a) => a && (item.name.toLowerCase().includes(a) || a.includes(item.name.toLowerCase())));
    totalCost += item.estimated_cost;
    if (isOwned) {
      ownedCount++;
    } else {
      missingCost += item.estimated_cost;
    }

    return {
      equipment_id: item.id,
      equipment_name: item.name,
      name: item.name,
      purpose: item.purpose,
      standard: item.standard,
      typical_quantity: item.typical_quantity,
      quantity: item.typical_quantity,
      estimated_cost: item.estimated_cost,
      unit_price: item.estimated_cost,
      priority: item.priority,
      essential: item.priority === 'Mandatory' ? 'Yes' : 'No',
      is_available: isOwned,
      status: isOwned ? 'owned' : 'missing',
    };
  });

  return {
    matched_business: {
      business_id: `MSME-${key.toUpperCase().slice(0, 4)}`,
      business_name: businessName || profile.categoryName,
      theme: profile.categoryName,
      category: category || profile.categoryName,
      standard_framework: profile.msmeStandard,
    },
    equipment_comparison: {
      total_count: equipmentList.length,
      total_mapped_equipment: equipmentList.length,
      available_count: ownedCount,
      missing_count: equipmentList.length - ownedCount,
      total_required_cost_inr: totalCost,
      estimated_missing_cost_inr: missingCost,
      all_mapped_equipment: equipmentList,
    },
  };
};
